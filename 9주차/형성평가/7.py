while True:
    cmd = input()
    
    if cmd == 'A':
        print("ADD")
    elif cmd == 'B':
        print("BACK")
    elif cmd == 'C':
        print("COPY")
    elif cmd == 'D':
        print("DELETE")
    elif cmd == 'E':
        print("EXIT")
        break
    else:
        print("NONE")
